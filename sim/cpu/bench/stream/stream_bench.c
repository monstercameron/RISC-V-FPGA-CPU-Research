/* SPDX-License-Identifier: MIT
 * Bare-metal STREAM-like bandwidth probe (run_bench.py --benchmark stream). Original code; it
 * follows the kernel definitions of McCalpin's STREAM (copy, scale, add, triad) but is not STREAM
 * and reports no STREAM result. 64-bit integer elements (the probe is for the integer core).
 *
 * Levels (footprints), in program order:
 *   0 dram  arrays in the loaded image (.data), never touched before their one timed pass: a first
 *           demand pass over lines no earlier demand access brought into the L2 (an L2 prefetcher may
 *           still have). Each kernel has its own arrays (STREAM_DRAM_WORDS each).
 *   1 l2    three .bss arrays of STREAM_L2_WORDS (larger than a 64 KiB L1, smaller than the L2):
 *           one untimed pass of the same kernel first, then one timed pass.
 *   2 l1    three .bss arrays of STREAM_L1_WORDS: one untimed pass, then STREAM_L1_REPS timed passes.
 * Kernels (slot k): 0 read s += x[i]; 1 write z[i] = 7; 2 copy z = x; 3 scale z = 3*y;
 *   4 add z = x + y; 5 triad z = x + 3*y; 6 chase: dependent loads, one per 64-byte line, visiting the
 *   footprint's lines in the order k -> (k + 389) mod lines (the next index is the loaded value), so
 *   neither value prediction nor a stream prefetcher can supply it: the load-to-use latency of the level.
 * Markers: 1 region start, 2 stop; call c = level * 8 + k is bracketed by laps 0x10 + 2c and 0x11 + 2c.
 * Mailbox (bench_result index): 0 magic "STRMBNCH", 1 mismatches (0 expected), 2 levels mask,
 *   3 + c the call's check word (sum read, or sum of the destination after the call).
 */
#include "bench.h"
#include <stdint.h>
#include <stddef.h>

#ifndef STREAM_DRAM_WORDS
#define STREAM_DRAM_WORDS 4096    /* 32 KiB per array: 512 cold lines */
#endif
#ifndef STREAM_L2_WORDS
#define STREAM_L2_WORDS 16384     /* 128 KiB per array: twice the 64 KiB L1 */
#endif
#ifndef STREAM_L1_WORDS
#define STREAM_L1_WORDS 512       /* 4 KiB per array */
#endif
#ifndef STREAM_L1_REPS
#define STREAM_L1_REPS 8
#endif
#ifndef STREAM_CHASE_WORDS
#define STREAM_CHASE_WORDS 4096   /* 32 KiB: 512 lines */
#endif
#ifndef STREAM_LEVELS
#define STREAM_LEVELS 7           /* bit 0 dram, 1 l2, 2 l1 */
#endif
#ifndef STREAM_KERNELS
#define STREAM_KERNELS 127        /* bit k: kernel slot k */
#endif
#define STREAM_MAGIC 0x48434e424d525453ull   /* "STRMBNCH", little endian */
#define K3 3u

#define DN STREAM_DRAM_WORDS
/* Cold arrays: generated by build_bench.py into stream_data.S (.data), so the bench loads them without
 * any bus or L2 traffic. Element i of array a holds i * 0x9e3779b97f4a7c15 + a * 0x632be59bd9b4e019
 * (values differ, so value prediction cannot supply them); d_q holds the chase's next word index. */
extern uint64_t d_x0[], d_z1[], d_x2[], d_z2[], d_y3[], d_z3[], d_x4[], d_y4[], d_z4[], d_x5[], d_y5[], d_z5[], d_q[];
static uint64_t l2_x[STREAM_L2_WORDS], l2_y[STREAM_L2_WORDS], l2_z[STREAM_L2_WORDS];
static uint64_t l1_x[STREAM_L1_WORDS], l1_y[STREAM_L1_WORDS], l1_z[STREAM_L1_WORDS];
static volatile uint64_t sink;

void *memcpy(void *d, const void *s, size_t n) {
    unsigned char *o = d;
    const unsigned char *i = s;
    while (n--) *o++ = *i++;
    return d;
}
void *memset(void *d, int c, size_t n) {
    unsigned char *o = d;
    while (n--) *o++ = (unsigned char)c;
    return d;
}

__attribute__((noinline)) static uint64_t k_read(const uint64_t *x, size_t n) {
    uint64_t s0 = 0, s1 = 0;
    for (size_t i = 0; i < n; i += 2) { s0 += x[i]; s1 += x[i + 1]; }
    return s0 + s1;
}
__attribute__((noinline)) static void k_write(uint64_t *z, size_t n) {
    for (size_t i = 0; i < n; i++) z[i] = 7;
}
__attribute__((noinline)) static void k_copy(uint64_t *z, const uint64_t *x, size_t n) {
    for (size_t i = 0; i < n; i++) z[i] = x[i];
}
__attribute__((noinline)) static void k_scale(uint64_t *z, const uint64_t *y, size_t n) {
    for (size_t i = 0; i < n; i++) z[i] = K3 * y[i];
}
__attribute__((noinline)) static void k_add(uint64_t *z, const uint64_t *x, const uint64_t *y, size_t n) {
    for (size_t i = 0; i < n; i++) z[i] = x[i] + y[i];
}
__attribute__((noinline)) static void k_triad(uint64_t *z, const uint64_t *x, const uint64_t *y, size_t n) {
    for (size_t i = 0; i < n; i++) z[i] = x[i] + K3 * y[i];
}
/* One load per 64-byte line; the loaded value is the next word index (a permutation of the lines), so
 * every load depends on the previous one and the values differ (no value prediction). */
__attribute__((noinline)) static uint64_t k_chase(const uint64_t *p, size_t lines) {
    uint64_t s = 0, j = 0;
    for (size_t i = 0; i < lines; i++) {
        uint64_t w = p[j];
        s += w;
        j = w;
    }
    return s;
}

static uint64_t sum(const uint64_t *z, size_t n) {
    uint64_t s = 0;
    for (size_t i = 0; i < n; i++) s += z[i];
    return s;
}

static uint64_t bad;

/* Run kernel k once on (z, x, y) of n words; returns the check word. */
static uint64_t call(int k, uint64_t *z, const uint64_t *x, const uint64_t *y, size_t n) {
    switch (k) {
    case 0: return k_read(x, n);
    case 1: k_write(z, n); return 0;
    case 2: k_copy(z, x, n); return 0;
    case 3: k_scale(z, y, n); return 0;
    case 4: k_add(z, x, y, n); return 0;
    case 5: k_triad(z, x, y, n); return 0;
    default: return k_chase(x, n / 8);
    }
}

/* Expected check word for kernel k over n words, from the sources (untimed): sums are linear. */
static uint64_t expect(int k, size_t n, const uint64_t *x, const uint64_t *y) {
    uint64_t sx = x ? sum(x, n) : 0, sy = y ? sum(y, n) : 0, lines = n / 8;   /* the chase visits every line once */
    return k == 0 ? sx : k == 1 ? 7 * (uint64_t)n : k == 2 ? sx : k == 3 ? K3 * sy : k == 4 ? sx + sy
         : k == 5 ? sx + K3 * sy : 8 * (lines * (lines - 1) / 2);
}

static void spacer(void) { for (int i = 0; i < 4; i++) sink = sink + 1; }

int main(void) {
    bench_result(0, STREAM_MAGIC);
    bench_result(2, STREAM_LEVELS | (uint64_t)STREAM_KERNELS << 8);
    bench_marker(BENCH_MARKER_START);
    if (STREAM_LEVELS & 1) {
        uint64_t *dz[7] = { 0, d_z1, d_z2, d_z3, d_z4, d_z5, 0 };
        const uint64_t *dx[7] = { d_x0, 0, d_x2, 0, d_x4, d_x5, d_q };
        const uint64_t *dy[7] = { 0, 0, 0, d_y3, d_y4, d_y5, 0 };
        for (int k = 0; k < 7; k++) {
            if (!(STREAM_KERNELS >> k & 1)) continue;
            size_t n = k == 6 ? STREAM_CHASE_WORDS : DN;
            spacer();
            bench_marker(0x10 + 2 * k);
            uint64_t r = call(k, dz[k], dx[k], dy[k], n);
            bench_marker(0x11 + 2 * k);
            if (k != 0 && k != 6) r = sum(dz[k], n);
            bad += r != expect(k, n, k == 6 ? 0 : dx[k], dy[k]);
            bench_result(3 + k, r);
        }
    }
    for (int level = 1; level <= 2; level++) {
        if (!(STREAM_LEVELS >> level & 1)) continue;
        uint64_t *x = level == 1 ? l2_x : l1_x, *y = level == 1 ? l2_y : l1_y, *z = level == 1 ? l2_z : l1_z;
        size_t n = level == 1 ? STREAM_L2_WORDS : STREAM_L1_WORDS;
        int reps = level == 1 ? 1 : STREAM_L1_REPS;
        for (size_t i = 0; i < n; i++) { x[i] = i * 0x9e3779b97f4a7c15ull + 1; y[i] = i * 0xbf58476d1ce4e5b9ull + 2; }
        for (int k = 0; k < 7; k++) {
            if (!(STREAM_KERNELS >> k & 1)) continue;
            int c = level * 8 + k;
            uint64_t r = 0;
            if (k == 6) {
                for (size_t i = 0; i < n; i++) x[i] = 8 * ((i / 8 + 389) % (n / 8));   /* the chase's next indexes */
                if (level == 1) { (void)k_read(y, n); (void)k_read(z, n); }   /* evict x from the L1 */
                else (void)call(k, z, x, y, n);
            } else (void)call(k, z, x, y, n);            /* warm pass, untimed */
            spacer();
            bench_marker(0x10 + 2 * c);
            for (int rep = 0; rep < reps; rep++) {
                r = call(k, z, x, y, n);
                __asm__ volatile("" ::: "memory");
            }
            bench_marker(0x11 + 2 * c);
            if (k != 0 && k != 6) r = sum(z, n);
            bad += r != expect(k, n, k == 6 ? 0 : x, y);
            bench_result(3 + c, r);
        }
    }
    spacer();
    bench_marker(BENCH_MARKER_STOP);
    bench_result(1, bad);
    return bad != 0;
}
