#!/bin/bash
# Build the lab-virt userland in an untracked work directory (default $HOME/linux-lab), in WSL with LLVM:
#   1. Linux UAPI headers (from the kernel tree, `make headers_install`) into the sysroot
#   2. musl 1.2.5 (MIT), static only, rv64gc lp64d
#   3. compiler-rt 18.1.3 builtins (Apache-2.0 WITH LLVM-exception) for riscv64: musl's long double
#      (IEEE binary128 on RISC-V) needs the __*tf3 routines, which Ubuntu's clang ships only for the host
#   4. busybox 1.37.0 (GPL-2.0), static, from allnoconfig plus sim/cpu/sys/busybox-lab.config
#   5. the initramfs list for the kernel's gen_init_cpio ($WORK/initramfs.list), with sim/cpu/sys/init.sh
# Every make or long command runs under `timeout 300`; rerun to resume. Sources: sim/cpu/sys/sources.lock.
#   sim/cpu/sys/build_userland.sh [WORK_DIR]
# SPDX-License-Identifier: MIT
set -e
HERE=$(cd "$(dirname "$0")" && pwd)
WORK=${1:-$HOME/linux-lab}
SYSROOT=$WORK/sysroot
JOBS=${JOBS:-3}
ARCHFLAGS="--target=riscv64-unknown-linux-musl -march=rv64gc -mabi=lp64d"
date "+%F %T %z build_userland start"
mkdir -p "$SYSROOT"

# 1. kernel UAPI headers
if [ ! -f "$SYSROOT/include/linux/version.h" ]; then
  timeout 300 make -C "$WORK/linux-6.18.64" O="$WORK/build-headers" ARCH=riscv LLVM=1 \
    INSTALL_HDR_PATH="$SYSROOT" headers_install > "$WORK/headers.log" 2>&1
  echo "headers installed"
fi

# 2. musl
if [ ! -f "$SYSROOT/lib/libc.a" ]; then
  mkdir -p "$WORK/build-musl"
  cd "$WORK/build-musl"
  if [ ! -f config.mak ]; then
    CC=clang CFLAGS="$ARCHFLAGS -O2" AR=llvm-ar RANLIB=llvm-ranlib \
      timeout 300 "$WORK/musl-1.2.5/configure" --target=riscv64 --prefix="$SYSROOT" --disable-shared \
      > configure.log 2>&1
  fi
  timeout 300 make -j"$JOBS" AR=llvm-ar RANLIB=llvm-ranlib > make.log 2>&1
  timeout 300 make install AR=llvm-ar RANLIB=llvm-ranlib > install.log 2>&1
  echo "musl installed"
fi

# 3. compiler-rt builtins
CRT=$WORK/compiler-rt-18.1.3.src/lib/builtins
if [ ! -f "$SYSROOT/lib/libclang_rt.builtins-riscv64.a" ]; then
  mkdir -p "$WORK/build-crt"
  cd "$WORK/build-crt"
  LIST=$(sed -n '/^set(GENERIC_SOURCES$/,/^)/p;/^set(GENERIC_TF_SOURCES$/,/^)/p' "$CRT/CMakeLists.txt" \
         | grep -E '^\s+[a-z0-9_]+\.c$' | grep -v -E 'apple_versioning|os_version_check|^\s*fp_mode\.c' )
  rm -f ./*.o
  for f in $LIST riscv/fp_mode.c; do
    timeout 300 clang $ARCHFLAGS -O2 -fPIC -fno-builtin -fvisibility=hidden -DVISIBILITY_HIDDEN \
      -I"$CRT" --sysroot="$SYSROOT" -isystem "$SYSROOT/include" -c "$CRT/$f" -o "$(basename "$f" .c).o"
  done
  llvm-ar rcs "$SYSROOT/lib/libclang_rt.builtins-riscv64.a" ./*.o
  echo "builtins: $(ls ./*.o | wc -l) objects"
fi

# 4. busybox, with a compiler driver for the musl sysroot: clang with compiler-rt's builtins in place of
#    libgcc, and musl's crt1/crti/crtn added explicitly on final links (there is no GCC installation to
#    supply crtbeginT.o and crtend.o, which a static C program does not need)
RES=$WORK/clang-resource
mkdir -p "$RES/lib/linux" "$WORK/bin"
ln -sfn "$(clang -print-resource-dir)/include" "$RES/include"
cp "$SYSROOT/lib/libclang_rt.builtins-riscv64.a" "$RES/lib/linux/"
CCW=$WORK/bin/rv64-musl-cc
cat > "$CCW" <<CCEOF
#!/bin/sh
# Generated by build_userland.sh. SPDX-License-Identifier: MIT
link=1
for a in "\$@"; do case "\$a" in -c|-S|-E|-M|-MM|-r|-nostdlib|-nostartfiles) link=0;; esac; done
set -- --target=riscv64-unknown-linux-musl -march=rv64gc -mabi=lp64d --sysroot=$SYSROOT -resource-dir=$RES \
  -rtlib=compiler-rt -unwindlib=none -fuse-ld=lld "\$@"
if [ \$link = 1 ]; then
  exec clang -nostartfiles $SYSROOT/lib/crt1.o $SYSROOT/lib/crti.o "\$@" $SYSROOT/lib/crtn.o
fi
exec clang "\$@"
CCEOF
chmod +x "$CCW"
BB=$WORK/build-busybox
if [ ! -x "$BB/busybox" ]; then
  mkdir -p "$BB"
  if [ ! -f "$BB/.config" ]; then
    timeout 300 make -C "$WORK/busybox-1.37.0" O="$BB" HOSTCC=clang allnoconfig > "$BB/config.log" 2>&1
    # kconfig keeps the first assignment of a symbol: drop allnoconfig's lines for our symbols first
    for sym in $(grep -o '^CONFIG_[A-Z0-9_]*' "$HERE/busybox-lab.config"); do
      sed -i -e "/^$sym=/d" -e "/^# $sym is not set/d" "$BB/.config"
    done
    grep '^CONFIG_' "$HERE/busybox-lab.config" >> "$BB/.config"
    yes "" | timeout 300 make -C "$WORK/busybox-1.37.0" O="$BB" HOSTCC=clang oldconfig >> "$BB/config.log" 2>&1 || true
  fi
  timeout 300 make -C "$BB" -j"$JOBS" HOSTCC=clang CC="$CCW"     AR=llvm-ar NM=llvm-nm STRIP=llvm-strip OBJCOPY=llvm-objcopy OBJDUMP=llvm-objdump     CFLAGS_EXTRA="-Wno-ignored-optimization-argument -Wno-unused-command-line-argument"     LDFLAGS="-static" SKIP_STRIP=y > "$BB/make.log" 2>&1 || { echo "busybox make failed"; tail -30 "$BB/make.log"; exit 1; }
  echo "busybox built"
fi
ls -l "$BB/busybox"

# 5. initramfs list (the kernel's gen_init_cpio format)
{
  echo "dir /dev 755 0 0"
  echo "nod /dev/console 600 0 0 c 5 1"
  echo "nod /dev/null 666 0 0 c 1 3"
  for d in proc sys bin sbin tmp root etc; do echo "dir /$d 755 0 0"; done
  echo "file /bin/busybox $BB/busybox 755 0 0"
  for a in $(grep -o '^CONFIG_[A-Z0-9_]*=y' "$HERE/busybox-lab.config" | sed -n 's/^CONFIG_\([A-Z0-9_]*\)=y/\1/p'); do
    case $a in
      ASH|SH_IS_ASH|STATIC|FEATURE_*|ASH_*|SH_IS_NONE|BASH_IS_NONE|LONG_OPTS|SHOW_USAGE|FEATURE|PLATFORM_LINUX) ;;
      *) echo "slink /bin/$(echo "$a" | tr 'A-Z_' 'a-z-') busybox 777 0 0" ;;
    esac
  done
  echo "slink /bin/sh busybox 777 0 0"
  echo "slink /sbin/poweroff ../bin/busybox 777 0 0"
  echo "file /init $HERE/init.sh 755 0 0"
} > "$WORK/initramfs.list"
echo "initramfs list: $(wc -l < "$WORK/initramfs.list") entries"
date "+%F %T %z build_userland end"
